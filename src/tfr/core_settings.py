def _setting(
    key: str,
    value_type: SettingType,
    default: object,
    scope: SettingScope,
    consumers: tuple[str, ...],
    *,
    restart: RestartRequirement = RestartRequirement.LIVE,
    sensitive: bool = False,
    nullable: bool = False,
    choices: tuple[object, ...] = (),
    minimum: int | float | None = None,
    maximum: int | float | None = None,
    minimum_length: int | None = None,
    maximum_length: int | None = None,
    pattern: str | None = None,
) -> SettingDescriptor:
    if (
        restart is RestartRequirement.LIVE
        and key.startswith("ui.")
        and key not in {"ui.spellcheck.enabled", "ui.speaking_streaks.enabled"}
    ):
        # Native UI state is constructed once at startup. Keep the small set of
        # settings with explicit live handlers live; report the rest honestly.
        restart = RestartRequirement.CLIENT_RESTART
    return SettingDescriptor(
        key=key,
        value_type=value_type,
        default=default,
        scope=scope,
        consumers=consumers,
        sensitivity=sensitive,
        restart=restart,
        validation=SettingValidation(
            nullable=nullable,
            choices=choices,
            minimum=minimum,
            maximum=maximum,
            minimum_length=minimum_length,
            maximum_length=maximum_length,
            pattern=pattern,
        ),
    )


def _theme_color_settings() -> Iterable[SettingDescriptor]:
    for name in (
        "background",
        "surface",
        "overlay",
        "text",
        "muted",
        "accent",
        "secondary",
        "info",
        "success",
        "warning",
        "error",
        "selection",
        "selected_text",
    ):
        yield _setting(
            f"ui.theme.colors.{name}",
            SettingType.STRING,
            None,
            SettingScope.UI_TYPE,
            NATIVE,
            nullable=True,
            pattern=r"#[0-9a-fA-F]{6}",
        )


